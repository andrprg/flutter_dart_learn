// ─── Задача 1 ─────────────────────────────────────────────────────
// Дан список целых чисел. Вернуть сумму всех элементов списка.
// Пустой список — вернуть 0.
// Исходные данные: [1, 2, 3, 4, 5]  → результат: 15
// Исходные данные: []               → результат: 0
import 'dart:math';

int sumList(List<int> list) {
  return list.fold<int>(0, (acc, curr) => acc + curr);
}

// ─── Задача 2 ─────────────────────────────────────────────────────
// Дан список чисел. Вернуть максимальный элемент.
// Если список пустой — вернуть null.
// Исходные данные: [3, 7, 2, 9, 1]   → результат: 9
// Исходные данные: []               → результат: null
int? maxInList(List<int> list) {
  if (list.isEmpty) return null;
  return list.reduce((acc, curr) => curr > acc ? curr : acc);
}

// ─── Задача 3 ─────────────────────────────────────────────────────
// Дан список. Вернуть новый список с элементами в обратном порядке.
// Исходный список не изменять.
// Исходные данные: [1, 2, 3, 4]     → результат: [4, 3, 2, 1]
// Исходные данные: ['a', 'b', 'c']  → результат: ['c', 'b', 'a']
List<T> reverseList<T>(List<T> list) {
  return list.reversed.toList();
}

// ─── Задача 4 ─────────────────────────────────────────────────────
// Дан список. Удалить все дубликаты, сохранив порядок первого вхождения.
// Вернуть новый список без дубликатов.
// Исходные данные: [1, 2, 2, 3, 1, 4, 2]  → результат: [1, 2, 3, 4]
// Исходные данные: ['x', 'x', 'y', 'x']   → результат: ['x', 'y']
List<T> removeDuplicates<T>(List<T> list) {
  return list.toSet().toList();
}

// ─── Задача 5 ─────────────────────────────────────────────────────
// Дан список целых чисел и порог N. Вернуть список только тех элементов,
// которые строго больше N.
// Исходные данные: [1, 5, 3, 8, 2], N = 3   → результат: [5, 8]
// Исходные данные: [10, 20, 30], N = 25     → результат: [30]
List<int> filterGreaterThan(List<int> list, int n) {
  return list.where((value) => value > n).toList();
}

// ─── Задача 6 ─────────────────────────────────────────────────────
// Дан список целых чисел. Вернуть индекс первого вхождения элемента value.
// Если элемента нет — вернуть -1.
// Исходные данные: [10, 20, 30, 20, 40], value = 20  → результат: 1
// Исходные данные: [1, 2, 3], value = 5              → результат: -1
int indexOfValue(List<int> list, int value) {
  return list.indexOf(value);
}

// ─── Задача 7 ─────────────────────────────────────────────────────
// Дан список списков (List<List<T>>). «Склеить» все вложенные списки
// в один плоский список (flatten).
// Исходные данные: [[1, 2], [3, 4], [5]]  → результат: [1, 2, 3, 4, 5]
// Исходные данные: [[], [1], [2, 3]]      → результат: [1, 2, 3]
List<T> flattenList<T>(List<List<T>> listOfLists) {
  return listOfLists.expand((a) => a).toList();
}

// ─── Задача 8 ─────────────────────────────────────────────────────
// Дан список и размер чанка size. Разбить список на подсписки длины size
// (последний может быть короче). Вернуть List<List<T>>.
// Исходные данные: [1, 2, 3, 4, 5, 6], size = 2  → результат: [[1, 2], [3, 4], [5, 6]]
// Исходные данные: [1, 2, 3, 4, 5], size = 3     → результат: [[1, 2, 3], [4, 5]]
List<List<T>> chunkList<T>(List<T> list, int size) {
  List<List<T>> result = [];
  for (var i = 0; i < list.length; i += size) {
    result.add(list.sublist(i, min(i + size, list.length)));
  }
  return result;
}

// ─── Задача 9 ─────────────────────────────────────────────────────
// Дан список целых чисел. Вернуть true, если список является палиндромом
// (читается одинаково слева направо и справа налево), иначе false.
// Исходные данные: [1, 2, 3, 2, 1]  → результат: true
// Исходные данные: [1, 2, 3, 4]     → результат: false
// Исходные данные: [5]              → результат: true
bool isPalindrome(List<int> list) {
  var reversed = list.reversed.toList();
  for (var i = 0; i < list.length; i++) {
    if (list[i] != reversed[i]) return false;
  }
  return true;
}

// ─── Задача 10 ─────────────────────────────────────────────────────
// Дан список целых чисел. Вернуть список без первого и последнего элемента.
// Если элементов меньше трёх — вернуть пустой список.
// Исходные данные: [10, 20, 30, 40]  → результат: [20, 30]
// Исходные данные: [1, 2]            → результат: []
// Исходные данные: [5, 6, 7]         → результат: [6]
List<int> withoutFirstAndLast(List<int> list) {
  if (list.length < 3) return [];
  return list.sublist(1, list.length - 1);
}

// ─── Задача 11 ─────────────────────────────────────────────────────
// Дан список целых чисел. Вернуть минимальный элемент.
// Если список пустой — вернуть null.
// Исходные данные: [3, 7, 2, 9, 1]   → результат: 1
// Исходные данные: [5]               → результат: 5
int? minInList(List<int> list) {
  if (list.isEmpty) return null;
  return list.reduce((acc, next) => acc < next ? acc : next);
}

// ─── Задача 12 ─────────────────────────────────────────────────────
// Дан список и значение. Вернуть количество вхождений value в списке.
// Исходные данные: [1, 2, 2, 3, 2, 4], value = 2   → результат: 3
// Исходные данные: [10, 20, 30], value = 5          → результат: 0
int countOccurrences<T>(List<T> list, T value) {
  return list.where((val) => val == value).length;
}

// ─── Задача 13 ─────────────────────────────────────────────────────
// Дан список и число n. Вернуть новый список из первых n элементов.
// Если n больше длины списка — вернуть копию всего списка.
// Исходные данные: [1, 2, 3, 4, 5], n = 3   → результат: [1, 2, 3]
// Исходные данные: [10, 20], n = 5          → результат: [10, 20]
List<T> takeFirst<T>(List<T> list, int n) {
  var len = list.length;
  return list.sublist(0, len < n ? len : n);
}

// ─── Задача 14 ─────────────────────────────────────────────────────
// Дан список и число n. Вернуть новый список без первых n элементов.
// Если n >= длины списка — вернуть пустой список.
// Исходные данные: [1, 2, 3, 4, 5], n = 2   → результат: [3, 4, 5]
// Исходные данные: [1, 2], n = 3            → результат: []
List<T> dropFirst<T>(List<T> list, int n) {
  return n > list.length ? [] : list.sublist(n);
}

// ─── Задача 15 ─────────────────────────────────────────────────────
// Дан список целых чисел. Вернуть среднее арифметическое (double).
// Пустой список — вернуть 0.0.
// Исходные данные: [10, 20, 30, 40]  → результат: 25.0
// Исходные данные: [1, 2, 3]        → результат: 2.0
double averageList(List<int> list) {
  if (list.isEmpty) return 0.0;
  return list.reduce((acc, curr) => acc + curr) / list.length;
}

