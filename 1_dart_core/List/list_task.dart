// ─── Задача 17 ─────────────────────────────────────────────────────
// Дан список целых чисел. Вернуть true, если все элементы чётные,
// иначе false. Пустой список считать «все чётные» → true.
// Исходные данные: [2, 4, 6, 8]   → результат: true
// Исходные данные: [2, 3, 4]      → результат: false
bool allEven(List<int> list) {
  if (list.isEmpty) return true;
  return list.every((value) => value % 2 == 0);
}

// ─── Задача 18 ─────────────────────────────────────────────────────
// Дан список целых чисел. Вернуть второй по величине элемент
// (уникальное значение, не индекс). Если элементов меньше двух — null.
// Исходные данные: [3, 1, 4, 1, 5]  → результат: 4
// Исходные данные: [10, 10, 5]      → результат: 5
int? secondLargest(List<int> list) {
  if (list.length < 2) return null;

  final unique = list.toSet().toList()..sort();
  if (unique.length < 2) return null;
  return unique[unique.length - 2];
}

// ─── Задача 19 ─────────────────────────────────────────────────────
// Дан список, индекс index и элемент value. Вставить value в позицию index,
// сдвинув остальные вправо. Вернуть новый список.
// Если index за пределами — вставить в конец или в начало по смыслу.
// Исходные данные: [1, 2, 4], index = 2, value = 3  → результат: [1, 2, 3, 4]
// Исходные данные: [10, 20], index = 0, value = 5   → результат: [5, 10, 20]
List<T> insertAt<T>(List<T> list, int index, T value) {
  if (index > list.length) return [...list, value];
  return [...list.sublist(0, index), value, ...list.sublist(index)];
}

// ─── Задача 20 ─────────────────────────────────────────────────────
// Дан список целых чисел. Вернуть список, в котором каждый элемент
// умножен на 2.
// Исходные данные: [1, 2, 3, 4]   → результат: [2, 4, 6, 8]
// Исходные данные: [0, -5, 10]    → результат: [0, -10, 20]
List<int> doubleEach(List<int> list) {
  if (list.isEmpty) return [];
  return list.map((value) => value * 2).toList();
}
